# Reference planet positions for tests/test_planets.c from JPL Horizons (DE441; NASA/JPL data, public): geocentric
# apparent ecliptic longitude and latitude of date (Horizons quantity 31), at seeded-random TT instants 1800-2199,
# and the motion in longitude over the day centred on each (from the longitudes 12 h before and after: deg/day).
# Writes tests/planet_ref.h. Needs the network (ssd.jpl.nasa.gov), only when regenerating; CI uses the header.
#   python3 tools/gen_planet_ref.py [N (120)] [SEED (7)]
# Neptune and Pluto are queried as their system barycentres (8, 9): Horizons has no Neptune-centre ephemeris after
# 2199-12-30; the barycentre offsets are < 0.1" (Triton) and < 0.2" (Charon) seen from the Earth.
import pathlib, random, sys, time, urllib.parse, urllib.request

BODIES = [("MERCURY", "199"), ("VENUS", "299"), ("MARS", "499"), ("JUPITER", "599"), ("SATURN", "699"),
          ("URANUS", "799"), ("NEPTUNE", "8"), ("PLUTO", "9")]
N = int(sys.argv[1]) if len(sys.argv) > 1 else 120
rng = random.Random(int(sys.argv[2]) if len(sys.argv) > 2 else 7)


def jd_tt(y, mo, d, h, mi, s):          # proleptic Gregorian civil date (TT) -> JD
    a = (14 - mo) // 12; yy = y + 4800 - a; mm = mo + 12 * a - 3
    jdn = d + (153 * mm + 2) // 5 + 365 * yy + yy // 4 - yy // 100 + yy // 400 - 32045
    return jdn - 0.5 + (h * 3600 + mi * 60 + s) / 86400


def horizons(cmd, jds):   # in chunks: a long time list makes the GET request too long for the server
    if len(jds) > 60: return horizons(cmd, jds[:60]) + horizons(cmd, jds[60:])
    q = {"format": "text", "COMMAND": f"'{cmd}'", "EPHEM_TYPE": "OBSERVER", "CENTER": "'500@399'",
         "TLIST": ",".join(f"'{j:.6f}'" for j in jds), "TLIST_TYPE": "JD", "TIME_TYPE": "TT",
         "QUANTITIES": "'31'", "ANG_FORMAT": "DEG", "CSV_FORMAT": "YES"}
    url = "https://ssd.jpl.nasa.gov/api/horizons.api?" + urllib.parse.urlencode(q)
    for i in range(5):
        try:
            t = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "astra-fm1-gen"}), timeout=60).read().decode()
            if "$$SOE" in t:
                rows = t[t.index("$$SOE") + 5:t.index("$$EOE")].strip().splitlines()
                if len(rows) != len(jds): raise SystemExit(f"Horizons gave {len(rows)} rows for {len(jds)} times")
                return [(float(r.split(",")[3]), float(r.split(",")[4])) for r in rows]
            raise RuntimeError(t[-300:])
        except Exception as e:
            print("retry", cmd, e, file=sys.stderr); time.sleep(5 * (i + 1))
    raise SystemExit(f"Horizons failed for {cmd}")


dates = [(2000, 1, 1, 12, 0, 0), (1800, 1, 2, 0, 0, 0), (2199, 12, 29, 0, 0, 0), (2026, 11, 5, 12, 0, 0)]
while len(dates) < N:
    dates.append((rng.randint(1800, 2199), rng.randint(1, 12), rng.randint(1, 28), rng.randint(0, 23), rng.randint(0, 59), 0))
dates = sorted(set(dates), key=lambda d: jd_tt(*d))   # Horizons answers in time order, whatever the request's order
jds = [jd_tt(*d) for d in dates]
cols = []
for name, cmd in BODIES:
    allj = sorted(set(jds) | {j - 0.5 for j in jds} | {j + 0.5 for j in jds})
    res = dict(zip(allj, horizons(cmd, allj)))
    cols.append([(res[j][0], res[j][1], ((res[j + 0.5][0] - res[j - 0.5][0] + 180) % 360) - 180) for j in jds]); time.sleep(1)
rows = []
for i, d in enumerate(dates):
    vals = ", ".join(f"{cols[b][i][0]:.7f}, {cols[b][i][1]:.7f}, {cols[b][i][2]:.7f}" for b in range(len(BODIES)))
    rows.append(f"  {{{d[0]},{d[1]},{d[2]},{d[3]},{d[4]},{d[5]}, {{{vals}}}}},")
p = pathlib.Path(__file__).resolve().parent.parent / "tests/planet_ref.h"
p.write_text("/* Generated by tools/gen_planet_ref.py from JPL Horizons (DE441): do not edit.\n"
             " * TT date/time; per body (" + " ".join(n for n, _ in BODIES) + "): apparent geocentric ecliptic\n"
             " * longitude and latitude of date (degrees), motion in longitude (degrees/day). */\n"
             f"#define PLANET_REF_BODIES {len(BODIES)}\n"
             "static const struct { int y, mo, d, h, mi, s; double v[PLANET_REF_BODIES][3]; } planet_ref[] = {\n"
             + "\n".join(rows) + "\n};\n")
print("wrote", p, len(rows), "rows")
