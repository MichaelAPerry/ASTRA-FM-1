# Generate core/astro/planet_tables.h from tools/data/vsop87d_trunc.txt and tools/data/pluto_cheb.txt (made by
# tools/fetch_ephem.py), in the device's integer units:
#   angles and L/B amplitudes: BAM (2^32 = 360 deg = 2 pi rad); R amplitudes and Pluto: au in Q23;
#   a term's argument: phase (BAM) + rate per day (BAM: integer + 12-bit fraction), as astro_lin_t.
# Floating point stays here, at build time.   python3 tools/gen_planet_tables.py
import math, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
BODIES = ["mer", "ven", "ear", "mar", "jup", "sat", "ura", "nep"]   # the VSOP87D index order of the tables
RAD = 2**32 / (2 * math.pi)
Q23 = 1 << 23


def bam(rad): return round((rad % (2 * math.pi)) * RAD) & 0xFFFFFFFF


def rate(c):   # rad per millennium -> BAM per day: integer, 12-bit fraction
    r = c / 365250 * RAD; ri = math.floor(r); rf = round((r - ri) * 4096)
    if rf == 4096: ri, rf = ri + 1, 0
    return ri & 0xFFFFFFFF, rf


terms = {(b, v, k): [] for b in BODIES for v in (1, 2, 3) for k in range(6)}
main = {}
for line in (ROOT / "tools/data/vsop87d_trunc.txt").read_text().splitlines():
    if line.startswith("#"): continue
    b, v, k, a, ph, c = line.split(); v, k, a, ph, c = int(v), int(k), float(a), float(ph), float(c)
    if v == 1 and k == 0 and c == 0.0: main.setdefault(b, [0.0, 0.0])[0] += a * math.cos(ph); continue   # constant
    if v == 1 and k == 1 and c == 0.0: main.setdefault(b, [0.0, 0.0])[1] += a * math.cos(ph); continue   # mean motion
    terms[(b, v, k)].append((a, ph, c))

out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
       "/* Generated by tools/gen_planet_tables.py from tools/data/ (VSOP87D truncated; Pluto fitted to JPL DE441): do not edit. */",
       "#ifndef PLANET_TABLES_H", "#define PLANET_TABLES_H",
       f"#define VSOP_NBODY {len(BODIES)}", "#define VSOP_EARTH 2",
       "/* VSOP87D terms: amplitude (L, B: BAM; R: au Q23), then the argument as astro_lin_t (phase, rate per day) */",
       "static const astro_vterm_t vsop_terms[] = {"]
idx = []
n = 0
for b in BODIES:
    for v in (1, 2, 3):
        row = []
        for k in range(6):
            row.append(n)
            for a, ph, c in terms[(b, v, k)]:
                amp = round(a * (Q23 if v == 3 else RAD)); ri, rf = rate(c)
                out.append(f"  {{{amp}, {{0x{bam(ph):08X}u, 0x{ri:08X}u, {rf}, 0}}}},"); n += 1
        row.append(n)
        idx.append(row)
out += ["};", "/* per body and variable (L, B, R): where the terms of power 0..5 start, and the end */",
        "static const uint16_t vsop_idx[VSOP_NBODY][3][7] = {"]
for i, b in enumerate(BODIES):
    out.append("  {" + ", ".join("{" + ",".join(str(x) for x in idx[3 * i + v]) + "}" for v in range(3)) + f"}},   /* {b} */")
out += ["};", "/* L's constant and mean motion, as astro_lin_t */", "static const astro_lin_t vsop_main[VSOP_NBODY] = {"]
for b in BODIES:
    c0, c1 = main[b]; ri, rf = rate(c1)
    out.append(f"  {{0x{bam(c0):08X}u, 0x{ri:08X}u, {rf}, 0}},   /* {b} */")
out.append("};")

lines = (ROOT / "tools/data/pluto_cheb.txt").read_text().splitlines()
hdr = lines[0].replace(";", " ").split()
j0, j1 = float(hdr[hdr.index("J0") + 1]), float(hdr[hdr.index("J1") + 1])
nseg, deg = int(hdr[hdr.index("n") + 1]), int(hdr[hdr.index("degree") + 1])
seg = (j1 - j0) / nseg
assert seg == int(seg) and (j0 - 2451545.0) % 1 == 0.5, "segments must be whole days, starting at 0h TT"
coef = {}
for line in lines[1:]:
    p = line.split(); coef[(int(p[0]), int(p[1]))] = [round(float(x) * Q23) for x in p[2:]]
d0 = math.floor(j0 - 2451545.0)          # astro_time_t of J0: days from J2000.0 and half a day
out += [f"#define PLUTO_NSEG {nseg}", f"#define PLUTO_DEG {deg}", f"#define PLUTO_SEG_DAYS {int(seg)}",
        f"#define PLUTO_D0 ({d0})   /* J0 = JD {j0} TT: astro_time_t {{PLUTO_D0, 32768}} */",
        "/* Pluto: Chebyshev coefficients, au Q23, per segment and coordinate (x, y, z; mean ecliptic of date) */",
        "static const int32_t pluto_cheb[PLUTO_NSEG][3][PLUTO_DEG + 1] = {"]
for k in range(nseg):
    out.append("  {" + ", ".join("{" + ",".join(str(v) for v in coef[(k, c)]) + "}" for c in range(3)) + "},")
out += ["};"]
# CORDIC: atan(2^-i) in BAM, and 1/K in Q30
out += ["/* CORDIC: atan(2^-i) in BAM, i = 0..29 */", "static const uint32_t cordic_atan[30] = {"]
out.append("  " + ",".join(f"{round(math.atan(2.0 ** -i) * RAD)}u" for i in range(30)))
k = 1.0
for i in range(30): k *= math.sqrt(1 + 2.0 ** (-2 * i))
out += ["};", f"#define CORDIC_INVK {round((1 / k) * 2**30)}   /* 1/K, Q30 */",
        "/* apparent place (Meeus 23.2, 32.3): aberration constant and e*k (BAM), the Earth's perihelion (BAM),",
        " * FK5 correction of VSOP87 longitudes (BAM), light time per au (days Q16 per au Q23, Q30) */",
        f"#define ABERR_K {round(20.49552 / 1296000 * 2**32)}", f"#define ABERR_EK {round(0.016708634 * 20.49552 / 1296000 * 2**32)}",
        f"#define ABERR_E {round(0.016708634 * 2**30)}   /* Q30 */",
        f"#define ABERR_PERI 0x{round(102.93735 / 360 * 2**32):08X}u", f"#define FK5_DL {round(-0.09033 / 1296000 * 2**32)}",
        f"#define LIGHT_Q30 {round(0.0057755183 * 65536 / Q23 * 2**30)}",
        "#endif", ""]
p = ROOT / "core/astro/planet_tables.h"
p.write_text("\n".join(out))
print(f"wrote {p}: {n} VSOP terms, Pluto {nseg}x3x{deg + 1}")
