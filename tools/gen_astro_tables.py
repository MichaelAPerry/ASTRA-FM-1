# Generate core/astro/astro_tables.h: the quarter-wave sine table and every astronomical constant, converted to the
# integer units the device uses (angles: BAM, 2^32 = 360 deg; rates: BAM per day = integer + 12-bit fraction).
# Coefficients are Meeus, Astronomical Algorithms 2nd ed.: ch. 25 (Sun, low precision), ch. 47 (Moon, main terms).
# The device has no FPU/libm, so floating point stays here, at build time.  python3 tools/gen_astro_tables.py
import math, pathlib
BAM = 2**32 / 360.0
def bam(deg): return round((deg % 360.0) * BAM) & 0xFFFFFFFF
def lin(name, a0, a1, a2=0.0):
    """angle = a0 + a1*T + a2*T^2 (T: Julian centuries TT from J2000), as (a0 BAM, per-day int, per-day frac12, T^2 coeff in BAM/4)"""
    r = a1 / 36525.0 * BAM
    ri = math.floor(r); rf = round((r - ri) * 4096)
    if rf == 4096: ri, rf = ri + 1, 0
    return f"  /* {name} */ {{0x{bam(a0):08X}u, 0x{ri & 0xFFFFFFFF:08X}u, {rf}, {round(a2 * BAM / 4)}}},"
els = [lin("SUN_L0", 280.46646, 36000.76983, 0.0003032), lin("SUN_M", 357.52911, 35999.05029, -0.0001537),
       lin("OMEGA", 125.04452, -1934.136261, 0.0020708),
       lin("MOON_LP", 218.3164477, 481267.88123421, -0.0015786), lin("MOON_D", 297.8501921, 445267.1114034, -0.0018819),
       lin("MOON_M", 357.5291092, 35999.0502909, -0.0001536), lin("MOON_MP", 134.9633964, 477198.8675055, 0.0087414),
       lin("MOON_F", 93.2720950, 483202.0175233, -0.0036539), lin("MOON_A1", 119.75, 131.849), lin("MOON_A2", 53.09, 479264.290)]
# Meeus table 47.A, longitude terms (D, M, M', F, coefficient in 1e-6 deg), largest first; the table's smallest 26 are left out
moon = [(0,0,1,0,6288774),(2,0,-1,0,1274027),(2,0,0,0,658314),(0,0,2,0,213618),(0,1,0,0,-185116),(0,0,0,2,-114332),
        (2,0,-2,0,58793),(2,-1,-1,0,57066),(2,0,1,0,53322),(2,-1,0,0,45758),(0,1,-1,0,-40923),(1,0,0,0,-34720),
        (0,1,1,0,-30383),(2,0,0,-2,15327),(0,0,1,2,-12528),(0,0,1,-2,10980),(4,0,-1,0,10675),(0,0,3,0,10034),
        (4,0,-2,0,8548),(2,1,-1,0,-7888),(2,1,0,0,-6766),(1,0,-1,0,-5163),(1,1,0,0,4987),(2,-1,1,0,4036),
        (2,0,2,0,3994),(4,0,0,0,3861),(2,0,-3,0,3665),(0,1,-2,0,-2689),(2,0,-1,2,-2602),(2,-1,-2,0,2390),
        (1,0,1,0,-2348),(2,-2,0,0,2236),(0,1,2,0,-2120),(0,2,0,0,-2069)]
N = 512   # quarter-wave segments
sin = [round(math.sin(i * math.pi / 2 / N) * (1 << 30)) for i in range(N + 1)]
deg_e6 = lambda c: round(c * 1e-6 * BAM)
out = ["/* SPDX-License-Identifier: GPL-3.0-only */", "/* Generated by tools/gen_astro_tables.py: do not edit. */",
       "#ifndef ASTRO_TABLES_H", "#define ASTRO_TABLES_H", f"#define ASTRO_SIN_N {N}",
       "static const int32_t sin_tab[ASTRO_SIN_N + 1] = {"]
out += ["  " + ",".join(str(v) for v in sin[i:i + 8]) + "," for i in range(0, N + 1, 8)]
out += ["};", "/* linear elements: a0 (BAM), rate per day (BAM, integer and /4096 fraction), T^2 coefficient (BAM/4) */",
        "static const astro_lin_t astro_el[] = {"] + els + ["};",
        "/* Moon longitude terms: D, M, M', F multipliers and the amplitude in BAM */",
        "static const astro_term_t moon_terms[] = {"]
out += [f"  {{{d},{m},{mp},{f},{deg_e6(c)}}}," for d, m, mp, f, c in moon]
out += ["};",
        "/* Sun equation of centre (BAM): sin M, its T coefficient, sin 2M, its T coefficient, sin 3M */",
        f"#define SUN_C1 {round(1.914602*BAM)}", f"#define SUN_C1T {round(-0.004817*BAM)}",
        f"#define SUN_C2 {round(0.019993*BAM)}", f"#define SUN_C2T {round(-0.000101*BAM)}", f"#define SUN_C3 {round(0.000289*BAM)}",
        f"#define SUN_ABERR {round(-0.00569*BAM)}",
        "/* nutation in longitude, Meeus 22 short form (BAM): sin Om, sin 2L(sun), sin 2L(moon), sin 2Om; Moon additive terms */",
        f"#define NUT_OM {round(-17.20/3600*BAM)}", f"#define NUT_2L {round(-1.32/3600*BAM)}", f"#define NUT_2LP {round(-0.23/3600*BAM)}", f"#define NUT_2OM {round(0.21/3600*BAM)}",
        f"#define MOON_A1T {deg_e6(3958)}", f"#define MOON_LFT {deg_e6(1962)}", f"#define MOON_A2T {deg_e6(318)}",
        "#endif", ""]
p = pathlib.Path(__file__).resolve().parent.parent / "core/astro/astro_tables.h"
p.write_text("\n".join(out))
print("wrote", p)
