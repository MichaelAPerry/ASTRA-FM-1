# ---- the planets (tests/sky_ref.h): apparent geocentric ecliptic longitude of date and its daily motion
import math
import astronomy.astronomy as _ae
BODIES = [astronomy.Body.Sun, astronomy.Body.Moon, astronomy.Body.Mercury, astronomy.Body.Venus, astronomy.Body.Mars,
          astronomy.Body.Jupiter, astronomy.Body.Saturn, astronomy.Body.Uranus, astronomy.Body.Neptune, astronomy.Body.Pluto]
def elon(body, t):
    if body == astronomy.Body.Sun: return astronomy.SunPosition(t).elon
    if body == astronomy.Body.Moon: return astronomy.EclipticGeoMoon(t).lon
    return astronomy.Ecliptic(astronomy.GeoVector(body, t, True)).elon      # true ecliptic of date, with aberration
rows = []
for y, mo, d, h, mi, s in dates:
    t = astronomy.Time.Make(y, mo, d, h, mi, s)
    lon = [elon(b, t) for b in BODIES]
    spd = [((elon(b, t.AddDays(0.25)) - elon(b, t.AddDays(-0.25)) + 540.0) % 360.0 - 180.0) * 2 for b in BODIES]
    rows.append(f"  {{{y},{mo},{d},{h},{mi},{s}, {{" + ",".join(f"{v:.6f}" for v in lon) + "}, {" + ",".join(f"{v:.6f}" for v in spd) + "}},")

# ---- angles and houses, from their definitions (not from the closed formulas the device uses):
# sidereal time and obliquity from Astronomy Engine; then geometry on unit vectors in the equator of date.
def unit(lam, eps): return (math.cos(lam), math.sin(lam) * math.cos(eps), math.sin(lam) * math.sin(eps))
def dot(a, b): return sum(x * y for x, y in zip(a, b))
def cross(a, b): return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])
def root(f, lo, hi):
    flo = f(lo)
    for _ in range(80):
        mid = (lo + hi) / 2
        if (f(mid) > 0) == (flo > 0): lo = mid
        else: hi = mid
    return (lo + hi) / 2
def roots(f, n=720):
    """every sign change of f on the circle"""
    out, xs = [], [2 * math.pi * i / n for i in range(n + 1)]
    for a, b in zip(xs, xs[1:]):
        if (f(a) > 0) != (f(b) > 0) and abs(f(a) - f(b)) < 1.0: out.append(root(f, a, b))
    return out
def wrap(x): return (x + math.pi) % (2 * math.pi) - math.pi
def houses(t, lat, lon):
    eps = math.radians(_ae._e_tilt(t).tobl)
    th = math.radians(astronomy.SiderealTime(t) * 15.0 + lon)
    phi = math.radians(lat)
    zen = (math.cos(phi) * math.cos(th), math.cos(phi) * math.sin(th), math.sin(phi))
    north = (-math.sin(phi) * math.cos(th), -math.sin(phi) * math.sin(th), math.cos(phi))
    east = (-math.sin(th), math.cos(th), 0.0)
    radec = lambda lam: (math.atan2(math.sin(lam) * math.cos(eps), math.cos(lam)), math.asin(math.sin(lam) * math.sin(eps)))
    # MC: on the meridian, south side (above the horizon for mid latitudes); ASC: on the horizon, rising (east)
    mc = [l for l in roots(lambda l: dot(unit(l, eps), east)) if abs(wrap(radec(l)[0] - th)) < 1][0]
    asc = [l for l in roots(lambda l: dot(unit(l, eps), zen)) if dot(unit(l, eps), east) > 0][0]
    def through(w):                              # the ecliptic point on the great circle through north and w, on w's side
        m = cross(north, w)
        return max(roots(lambda l: dot(unit(l, eps), m)), key=lambda l: dot(unit(l, eps), w))
    regio = [through((math.cos(th + a), math.sin(th + a), 0.0)) for a in map(math.radians, (30, 60, 120, 150))]
    camp = [through(tuple(math.cos(a) * z + math.sin(a) * e for z, e in zip(zen, east))) for a in map(math.radians, (30, 60, 120, 150))]
    def sa(dec): return math.acos(-math.tan(phi) * math.tan(dec))          # semi-diurnal arc
    def plac(f, below):
        def g(l):
            ra, dec = radec(l)
            return (wrap(th + math.pi - ra) - f * (math.pi - sa(dec))) if below else (wrap(ra - th) - f * sa(dec))
        want = wrap(mc + (math.pi - f * math.pi / 2 if below else f * math.pi / 2) - 0)   # near the equal-division place
        return min(roots(g), key=lambda l: abs(wrap(l - want)))
    placidus = [plac(1 / 3, 0), plac(2 / 3, 0), plac(2 / 3, 1), plac(1 / 3, 1)]
    def asc_at(th2):                             # Koch: the ascendant at another sidereal time
        z2 = (math.cos(phi) * math.cos(th2), math.cos(phi) * math.sin(th2), math.sin(phi)); e2 = (-math.sin(th2), math.cos(th2), 0.0)
        return [l for l in roots(lambda l: dot(unit(l, eps), z2)) if dot(unit(l, eps), e2) > 0][0]
    s = sa(radec(mc)[1])
    koch = [asc_at(th - 2 * s / 3), asc_at(th - s / 3), asc_at(th + s / 3), asc_at(th + 2 * s / 3)]
    return [math.degrees(v) % 360.0 for v in [asc, mc] + placidus + koch + regio + camp]
hrng = random.Random(2)
hrows = []
for i, (y, mo, d, h, mi, s) in enumerate(dates[:60]):
    t = astronomy.Time.Make(y, mo, d, h, mi, s)
    lat = [51.5, -33.9, 0.0, 40.7, 60.0, -55.0][i] if i < 6 else hrng.uniform(-62.0, 62.0)
    lon = [-0.1, 151.2, 0.0, -74.0, 25.0, -68.0][i] if i < 6 else hrng.uniform(-180.0, 180.0)
    lat, lon = round(lat, 3), round(lon, 3)
    hrows.append(f"  {{{y},{mo},{d},{h},{mi},{s}, {lat:.3f}, {lon:.3f}, {{" + ",".join(f"{v:.5f}" for v in houses(t, lat, lon)) + "}},")
