# Reference positions for tests/test_astro.c, from Astronomy Engine (Don Cross, MIT, pip install astronomy-engine):
# an independent, higher-precision model (VSOP87 / full lunar theory). Writes tests/astro_ref.h. Inputs are UTC.
#   python3 tools/gen_reference.py
import pathlib, random, astronomy
rng = random.Random(1)
dates = [(2000,1,1,12,0,0),(1992,4,12,0,0,0),(1992,10,13,0,0,0),(2024,3,20,3,6,0),(1987,9,23,0,0,0),
         (1800,1,1,0,0,0),(2199,12,31,23,59,59),(2026,11,5,17,0,0),(1969,7,20,20,17,0)]
while len(dates) < 120:
    dates.append((rng.randint(1800, 2199), rng.randint(1, 12), rng.randint(1, 28), rng.randint(0, 23), rng.randint(0, 59), rng.randint(0, 59)))
rows = []
for y, mo, d, h, mi, s in dates:
    t = astronomy.Time.Make(y, mo, d, h, mi, s)
    sun = astronomy.SunPosition(t).elon
    moon = astronomy.EclipticGeoMoon(t).lon
    rows.append(f"  {{{y},{mo},{d},{h},{mi},{s}, {sun:.6f}, {moon:.6f}}},")
p = pathlib.Path(__file__).resolve().parent.parent / "tests/astro_ref.h"
p.write_text("/* Generated by tools/gen_reference.py from Astronomy Engine 2.x: do not edit.\n"
             " * UTC date/time, Sun apparent ecliptic longitude of date, Moon ecliptic longitude of date (degrees). */\n"
             "static const struct { int y, mo, d, h, mi, s; double sun, moon; } astro_ref[] = {\n" + "\n".join(rows) + "\n};\n")
print("wrote", p, len(rows), "rows")
