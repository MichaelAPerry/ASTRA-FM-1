             " * Houses: latitude, east longitude; ASC, MC, then cusps 11 12 2 3 of Placidus, Koch, Regiomontanus, Campanus,\n"
             " * each found from its definition by root finding on unit vectors (sidereal time and obliquity: Astronomy Engine). */\n"
