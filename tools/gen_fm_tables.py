# Generate core/fm/fm_tables.h: the FM engine's constants in its integer units (the device has no FPU).
#   python3 tools/gen_fm_tables.py
import math, pathlib
FS, SUB = 44100.0, 32
out = ["/* SPDX-License-Identifier: GPL-3.0-only */", "/* Generated by tools/gen_fm_tables.py: do not edit. */",
       "#ifndef FM_TABLES_H", "#define FM_TABLES_H"]
def tab(ctype, name, vals, per=12, fmt="{}"):
    out.append(f"static const {ctype} {name}[{len(vals)}] = {{")
    out.extend("  " + ",".join(fmt.format(v) for v in vals[i:i + per]) + "," for i in range(0, len(vals), per))
    out.append("};")
# phase steps of MIDI notes 120..131 (C9..B9) at 44.1 kHz; note n: fm_inc_top[n % 12] >> (10 - n / 12)
out.append("/* phase step (2^32 a cycle) of MIDI notes 120..131 */")
tab("uint32_t", "fm_inc_top", [round(440.0 * 2 ** ((n - 69) / 12) * 2 ** 32 / FS) for n in range(120, 132)], 6, "{}u")
# a quarter sine, 1024 steps, Q15
out.append("/* sin(i * pi / 2048), Q15 */")
tab("int16_t", "fm_qsin", [min(32767, round(math.sin(i * math.pi / 2048) * 32768)) for i in range(1025)], 16)
# level 0..127 -> amplitude Q15: 0.5 dB a step below 127, 0 at 0 (63 dB of range, as an FM operator's level)
out.append("/* level 0..127 to amplitude Q15: 0.5 dB a step */")
tab("uint16_t", "fm_level_tab", [0] + [round(32767 * 10 ** (-0.5 * (127 - p) / 20)) for p in range(1, 128)], 16)
# envelope time 0..127 -> the fraction of the remaining distance covered per sub-block, Q20: 1.5 ms .. 12 s
out.append("/* envelope time 0..127 to the per-sub-block approach coefficient, Q20 (time constant 1.5 ms .. 12 s) */")
tab("uint32_t", "fm_env_tab", [min(393216, round((1 << 20) * (1 - math.exp(-(SUB / FS) / (0.0015 * 8000 ** (p / 127)))))) for p in range(128)], 12)
# the waves' harmonic recipes: (harmonic, weight Q12, quarter-turn phase) and the gain that brings the peak to 32767
def peak(h):
    return max(abs(sum(w * math.sin(k * 2 * math.pi * i / 4096 + q * math.pi / 2) for k, w, q in h)) for i in range(4096))
WAVES = {"AIR": [(1, 1.0, 0)],
         "FIRE": [(1, 1.0, 0), (2, 0.5, 0), (3, 0.33, 0), (4, 0.2, 0)],
         "EARTH": [(1, 1.0, 0), (3, 0.34, 0), (5, 0.16, 0)],
         "WATER": [(1, 1.0, 0), (2, 0.42, 1), (4, 0.07, 1)]}
out.append("/* the four element waves as sums of harmonics: harmonic, weight Q12 (scaled so the peak is full scale), phase in quarter turns */")
out.append("typedef struct { uint8_t h, q; int16_t w; } fm_harm_t;")
rows, starts = [], [0]
for name, h in WAVES.items():
    g = 1.0 / peak(h)
    rows += [f"  {{{k}, {q}, {round(w * g * 4096)}}},   /* {name} */" for k, w, q in h]
    starts.append(len(rows))
out.append(f"static const fm_harm_t fm_harm[{len(rows)}] = {{")
out += rows + ["};", "static const uint8_t fm_harm_at[5] = {" + ",".join(map(str, starts)) + "};"]
# prime delay lengths for the reverb, and its input allpasses
out.append("#endif")
out.append("")
p = pathlib.Path(__file__).resolve().parent.parent / "core/fm/fm_tables.h"
p.write_text("\n".join(out))
print("wrote", p)
